import { chromium } from 'playwright-core';
import fs from 'fs';
import path from 'path';
const dist = path.resolve('dist');
const out = process.argv[2];
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.glb': 'model/gltf-binary', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.mp3': 'audio/mpeg', '.hdr': 'application/octet-stream', '.woff2': 'font/woff2', '.wasm': 'application/wasm' };
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('error', m.text().slice(0, 300)); });
await page.route('http://surge.test/**', async (route) => {
  const url = new URL(route.request().url());
  let file = path.join(dist, decodeURIComponent(url.pathname));
  if (url.pathname === '/' || !fs.existsSync(file) || fs.statSync(file).isDirectory()) file = path.join(dist, 'index.html');
  await route.fulfill({ status: 200, body: fs.readFileSync(file), contentType: types[path.extname(file)] ?? 'application/octet-stream' });
});
await page.goto('http://surge.test/?menu=heroes&reel=0', { waitUntil: 'load' });
await page.waitForTimeout(14000);
const click = async (id) => {
  const p = await page.evaluate((i) => window.__surgeWidget(i), id);
  console.log(id, JSON.stringify(p));
  if (!p) return;
  await page.mouse.click(((p[0] + 1) / 2) * 1280, ((1 - p[1]) / 2) * 720);
  await page.waitForTimeout(5000);
};
await click('back');
await click('settings');
await page.waitForTimeout(3000);
await page.screenshot({ path: path.join(out, 'audit-settings.png') });
await browser.close();
// combat smoke: boots a mission, spawns enemies, reads the perf readout, reports errors
const b2 = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const p2 = await b2.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
p2.on('pageerror', (e) => errs.push('PAGEERROR ' + e.message));
p2.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 300)); });
await p2.route('http://surge.test/**', async (route) => {
  const url = new URL(route.request().url());
  let file = path.join(dist, decodeURIComponent(url.pathname));
  if (url.pathname === '/' || !fs.existsSync(file) || fs.statSync(file).isDirectory()) file = path.join(dist, 'index.html');
  await route.fulfill({ status: 200, body: fs.readFileSync(file), contentType: types[path.extname(file)] ?? 'application/octet-stream' });
});
await p2.goto('http://surge.test/?autostart=ember-foundry-1&hero=ronin&skipstory=1&dtmax=0.2&reel=0', { waitUntil: 'load' });
await p2.waitForTimeout(24000);
await p2.evaluate('window.__surgeSpawn("blade",3);window.__surgeSpawn("drone",2)');
await p2.waitForTimeout(16000);
console.log('combat errors:', JSON.stringify(errs));
console.log(JSON.stringify(await p2.evaluate(() => window.__surgePerf && window.__surgePerf())));
await p2.screenshot({ path: path.join(out, 'audit-combat.png') });
await b2.close();
